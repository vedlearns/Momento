package com.momento.album.domain;

import java.io.Serializable;
import java.util.Objects;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Embeddable;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;

/** Composite primary key of album_media: (album_id, media_item_id). */
/**
 * Serializable is a marker interface provided by Java.
 *
 * Serialization:
 * Converts a Java object into a byte stream so that its state
 * can be stored or transferred.
 *
 * Deserialization:
 * Converts the byte stream back into the original Java object.
 *
 * Why do we implement Serializable here?
 * JPA expects a composite primary key class to implement
 * Serializable.
 *
 * Serializable is an interface, not a class.
 * It is called a marker interface because it does not contain
 * any methods that we need to implement.
 *
 * In our Momento project:
 * AlbumMediaId contains two UUIDs:
 * 1. albumId
 * 2. mediaItemId
 *
 * Together, these two UUIDs represent the composite primary key
 * of the album_media table.
 */
@Embeddable
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class AlbumMediaId implements Serializable {
	
	/*
	 * Why are we not using @Id and @GeneratedValue here?
	 *
	 * 1. albumId already exists in the albums table.
	 *    It is generated when a new album is created.
	 *
	 * 2. mediaItemId already exists in the media_items table.
	 *    It is generated when a new photo/video is uploaded.
	 *
	 * 3. Here, we are not creating new UUIDs.
	 *    We are simply combining these two existing UUIDs
	 *    to create a Composite Primary Key.
	 *
	 * 4. @Id is not needed on these individual fields because
	 *    @EmbeddedId in the AlbumMedia entity tells JPA that
	 *    both fields together form the Primary Key.
	 *
	 * 5. @GeneratedValue is not needed because these IDs
	 *    are already generated by their respective entities.
	 *
	 * In short:
	 * albumId + mediaItemId = Composite Primary Key.
	 */
    @Column(name = "album_id", nullable = false)
    private UUID albumId;

    @Column(name = "media_item_id", nullable = false)
    private UUID mediaItemId;
	
    public AlbumMediaId(UUID albumId, UUID mediaItemId) {
        this.albumId = albumId;
        this.mediaItemId = mediaItemId;
    }
    
    
    /*
     * Why do we override equals() and hashCode()?
     *
     * By default, Java's equals() compares object references,
     * meaning it checks whether two references point to the
     * exact same object in memory.
     *
     * But in our case, we want to compare the actual values
     * inside two AlbumMediaId objects.
     *
     * Example:
     * AlbumMediaId id1 = new AlbumMediaId(A1, M1);
     * AlbumMediaId id2 = new AlbumMediaId(A1, M1);
     *
     * Both objects have the same albumId and mediaItemId,
     * but they are two different objects in memory.
     *
     * equals():
     * Checks whether both objects contain the same albumId
     * AND mediaItemId.
     *
     * hashCode():
     * Generates a hash value using both albumId and mediaItemId.
     *
     * Why are both needed?
     * Java collections like HashSet and HashMap use hashCode()
     * and equals() to identify and compare objects.
     *
     * Important rule:
     * If two objects are equal according to equals(),
     * they must have the same hashCode().
     *
     * In our project:
     * Both objects should be considered equal if they represent
     * the same album_id + media_item_id combination,
     * regardless of whether they are separate Java objects.
     */
    
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof AlbumMediaId other)) return false;
        return Objects.equals(albumId, other.albumId)
                && Objects.equals(mediaItemId, other.mediaItemId);
    }

    @Override
    public int hashCode() {
        return Objects.hash(albumId, mediaItemId);
    }

	
}
