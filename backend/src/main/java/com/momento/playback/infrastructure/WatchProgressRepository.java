package com.momento.playback.infrastructure;

import java.util.Optional;
import java.util.UUID;

import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Slice;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;

import com.momento.playback.domain.WatchProgress;

public interface WatchProgressRepository extends JpaRepository<WatchProgress, UUID> {

    Optional<WatchProgress> findByUserIdAndMediaItemId(UUID userId, UUID mediaItemId);

    /** "Continue watching" row: started but not finished, most recent first. */
    Slice<WatchProgress> findByUserIdAndCompletedFalseOrderByLastWatchedAtDesc(UUID userId, Pageable pageable);

    /**
     * UPSERT (UPDATE + INSERT):
     *
     * This query inserts a new playback progress record if one doesn't exist.
     * If a record already exists for the same user and video, it updates that record.
     *
     * 1. @Modifying:
     *    Tells Spring Data JPA that this query changes database data
     *    instead of just fetching data.
     *
     *    - flushAutomatically = true:
     *      Saves pending Hibernate changes before executing this query.
     *
     *    - clearAutomatically = true:
     *      Clears Hibernate's persistence context after execution so it
     *      doesn't keep outdated entity data in memory.
     *
     * 2. INSERT INTO:
     *    Specifies the watch_progress table and the columns where
     *    playback progress will be stored.
     *
     * 3. VALUES:
     *    Supplies the values received from the Java method:
     *    - userId: ID of the user watching the video.
     *    - mediaItemId: ID of the video being watched.
     *    - positionMs: Current playback position in milliseconds.
     *    - completed: Whether the video has been completed.
     *    - now(): Current timestamp generated by PostgreSQL.
     *
     * 4. ON CONFLICT (user_id, media_item_id):
     *    Our database has a UNIQUE constraint on these two columns.
     *    This means one user can have only one progress record per video.
     *
     *    - If the record doesn't exist, INSERT creates a new record.
     *    - If the record already exists, DO UPDATE updates the existing record.
     *
     * 5. EXCLUDED:
     *    A PostgreSQL keyword that refers to the new values we attempted
     *    to insert but couldn't because a matching record already existed.
     *
     *    We use these new values to update:
     *    - position_ms
     *    - completed
     *
     *    last_watched_at is refreshed with the current database timestamp.
     *
     * 6. nativeQuery = true:
     *    Tells Spring Data JPA to execute this as native SQL.
     *    We need it because PostgreSQL's ON CONFLICT syntax is not supported
     *    by standard JPQL.
     *
     * 7. @Param:
     *    Connects Java method parameters with the named placeholders
     *    in the SQL query, such as :userId and :positionMs.
     *
     * 8. Return type int:
     *    Returns the number of database rows affected (normally 1).
     *
     * WHY UPSERT?
     * The video player sends playback updates repeatedly.
     * Instead of checking whether a record exists and then inserting
     * or updating it separately, PostgreSQL handles both operations
     * in one atomic query.
     *
     * Example:
     * First update: 2 minutes -> INSERT a new record.
     * Second update: 4 minutes -> UPDATE the existing record.
     * Third update: 6 minutes -> UPDATE the same record.
     *
     * Result: Only one progress record exists for that user and video.
     */
    @Modifying(clearAutomatically = true, flushAutomatically = true)
    @Query(value = """
            insert into watch_progress (user_id, media_item_id, position_ms, completed, last_watched_at)
            values (:userId, :mediaItemId, :positionMs, :completed, now())
            on conflict (user_id, media_item_id) do update
               set position_ms = excluded.position_ms,
                   completed = excluded.completed,
                   last_watched_at = now()
            """, nativeQuery = true)
    int upsert(@Param("userId") UUID userId,
               @Param("mediaItemId") UUID mediaItemId,
               @Param("positionMs") long positionMs,
               @Param("completed") boolean completed);
}
